"""In-cluster DNSSync integration runner.

Runs the *real* ``python -m dnssync`` CLI as a subprocess against the real
BIND server in this Kubernetes cluster, and verifies the results with
*independent* dnspython queries -- never by inspecting BIND's internals. This
mirrors the seven behavior scenarios from ``tests/test_e2e.py`` (minus the
unreachable-server case, which needs no live BIND).

Configuration is injected via environment variables (set by the orchestrator
Job) so nothing test-specific is hard-coded here:

  DNSSYNC_BIND_HOST    BIND Service hostname (resolved to its ClusterIP here)
  DNSSYNC_ZONE         zone origin, absolute FQDN with trailing dot
  DNSSYNC_TSIG_KEY     TSIG key name (FQDN)
  DNSSYNC_TSIG_SECRET  TSIG secret (base64)

The zone file to sync is mounted read-only at ``/cfg/zone.zone``; the DNSSync
package is reconstituted at ``/app/src/dnssync`` by the Pod bootstrap, so
``PYTHONPATH=/app/src`` makes ``python -m dnssync`` import the *current*
source (always regenerated by the orchestrator from the working tree).
"""

import base64
import os
import socket
import subprocess
import sys

import dns.message
import dns.query
import dns.rdatatype

BIND_HOST = os.environ["DNSSYNC_BIND_HOST"]
ZONE = os.environ["DNSSYNC_ZONE"]
KEY = os.environ["DNSSYNC_TSIG_KEY"]
SECRET = os.environ["DNSSYNC_TSIG_SECRET"]
PORT = 53

ZONEFILE_SRC = "/cfg/zone.zone"   # read-only mount of the fixture
ZONEFILE = "/tmp/zone.zone"       # writable working copy the CLI reads

# dnspython's query helpers need an IP address, not a Service hostname, so
# resolve the ClusterIP via the Pod's DNS first.
BIND_IP = socket.gethostbyname(BIND_HOST)
print(f"[runner] {BIND_HOST} -> {BIND_IP}", flush=True)

ORIGIN = ZONE
WWW = "www." + ZONE
API = "api." + ZONE
MAIL = "mail." + ZONE
SHOP = "shop." + ZONE
MANAGED = [ORIGIN, WWW, API, MAIL]

RESULTS = []


def report(name, ok, detail=""):
    RESULTS.append((name, ok, detail))
    tag = "PASS" if ok else "FAIL"
    print(f"[{tag}] {name}  {detail}", flush=True)


def finish():
    print("\n=== SUMMARY ===", flush=True)
    for name, ok, detail in RESULTS:
        print(f"  {'PASS' if ok else 'FAIL'}  {name}  {detail}", flush=True)
    if RESULTS and all(ok for _, ok, _ in RESULTS):
        print("ALL_SCENARIOS_PASSED", flush=True)
        sys.exit(0)
    print("SOME_SCENARIOS_FAILED", flush=True)
    sys.exit(1)


# --------------------------------------------------------------------------- #
# independent verification (queries the server directly, not via DNSSync)
# --------------------------------------------------------------------------- #

def _rrsets(name, rdtype):
    ans = dns.query.udp(
        dns.message.make_query(name, rdtype), BIND_IP, port=PORT, timeout=5
    )
    return list(ans.answer)


def q_a(name):
    out = set()
    for rr in _rrsets(name, dns.rdatatype.A):
        for r in rr:
            out.add(str(r))
    return out


def q_txt(name):
    out = []
    for rr in _rrsets(name, dns.rdatatype.TXT):
        for r in rr:
            out.append(str(r))
    return out


def q_ns(name):
    out = set()
    for rr in _rrsets(name, dns.rdatatype.NS):
        for r in rr:
            out.add(str(r))
    return out


# --------------------------------------------------------------------------- #
# DNSSync CLI invocation (real entry point, subprocess)
# --------------------------------------------------------------------------- #

def run_cli(dry_run=False, secret=SECRET):
    cmd = [
        sys.executable, "-m", "dnssync", ZONEFILE,
        "-s", BIND_IP, "-p", str(PORT), "-z", ZONE,
        "-k", KEY, "--key-secret", secret,
    ]
    if dry_run:
        cmd.append("--dry-run")
    env = dict(os.environ, PYTHONPATH="/app/src")
    return subprocess.run(cmd, capture_output=True, text=True, timeout=120, env=env)


def write_zone(text):
    with open(ZONEFILE, "w") as f:
        f.write(text)
    return ZONEFILE


# --------------------------------------------------------------------------- #
# zone-file transformation helpers (line-based, whitespace-tolerant)
# --------------------------------------------------------------------------- #

with open(ZONEFILE_SRC) as f:
    ORIGINAL = f.read()


def transform(original, www_ip=None, drop=(), add=None):
    """Return *original* with the www A record changed / named lines dropped /
    extra lines appended. Matches on the first token of each record line."""
    out = []
    for line in original.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("$"):
            out.append(line)
            continue
        name = stripped.split()[0]
        if name in drop:
            continue
        if www_ip is not None and name == "www":
            out.append(f"www     IN  A   {www_ip}")
        else:
            out.append(line)
    if add:
        out.extend(add)
    return "\n".join(out) + "\n"


# --------------------------------------------------------------------------- #
# scenarios (run in sequence against one persistent BIND)
# --------------------------------------------------------------------------- #

def s1_first_sync():
    write_zone(ORIGINAL)
    r = run_cli()
    if r.returncode != 0:
        report("first_sync", False, f"rc={r.returncode} :: {r.stdout}\n{r.stderr}")
        return
    ok = (
        q_a(ORIGIN) == {"10.0.0.1"}
        and q_a(WWW) == {"10.0.0.1"}
        and q_a(API) == {"10.0.0.2"}
        and q_a(MAIL) == {"10.0.0.3"}
        and "ns1." + ZONE in q_ns(ORIGIN)
        and "ns2." + ZONE in q_ns(ORIGIN)
    )
    report("first_sync", ok,
           f"@={q_a(ORIGIN)} www={q_a(WWW)} api={q_a(API)} mail={q_a(MAIL)} ns={q_ns(ORIGIN)}")


def s2_heritage_markers():
    flags = {}
    for name in MANAGED:
        txts = q_txt(name)
        flags[name.split(ZONE)[0].rstrip(".")] = any(
            "heritage=external-dns" in t for t in txts
        )
    ok = all(flags.values())
    report("heritage_markers", ok, str(flags))


def s3_idempotency():
    before = q_a(WWW)
    r = run_cli()
    if r.returncode != 0:
        report("idempotency", False, f"rc={r.returncode} :: {r.stdout}\n{r.stderr}")
        return
    after = q_a(WWW)
    no_op = ("already in sync" in r.stdout)
    ok = (before == after == {"10.0.0.1"}) and no_op
    report("idempotency", ok, f"before={before} after={after} no_op={no_op}")


def s4_change_detection():
    write_zone(transform(ORIGINAL, www_ip="10.9.9.9",
                         add=["shop    IN  A   10.0.0.4"]))
    r = run_cli()
    if r.returncode != 0:
        report("change_detection", False, f"rc={r.returncode} :: {r.stdout}\n{r.stderr}")
        return
    ok = (
        q_a(WWW) == {"10.9.9.9"}
        and q_a(SHOP) == {"10.0.0.4"}
        and q_a(MAIL) == {"10.0.0.3"}
    )
    report("change_detection", ok,
           f"www={q_a(WWW)} shop={q_a(SHOP)} mail={q_a(MAIL)}")


def s5_stale_deletion():
    write_zone(transform(ORIGINAL, drop=("api",)))
    r = run_cli()
    if r.returncode != 0:
        report("stale_deletion", False, f"rc={r.returncode} :: {r.stdout}\n{r.stderr}")
        return
    ok = (
        q_a(API) == set()          # A record removed
        and q_txt(API) == []       # ...and its heritage TXT is not orphaned
        and q_a(MAIL) == {"10.0.0.3"}
    )
    report("stale_deletion", ok, f"api_A={q_a(API)} api_TXT={q_txt(API)} mail={q_a(MAIL)}")


def s6_dry_run():
    before = q_a(WWW)
    write_zone(transform(ORIGINAL, www_ip="99.99.99.99"))
    r = run_cli(dry_run=True)
    if r.returncode != 0:
        report("dry_run", False, f"rc={r.returncode} :: {r.stdout}\n{r.stderr}")
        return
    after = q_a(WWW)
    ok = (before == after) and ("Dry run complete" in r.stdout)
    report("dry_run", ok, f"before={before} after={after} msg={'Dry run complete' in r.stdout}")


def s7_auth_failure():
    before = q_a(WWW)
    write_zone(transform(ORIGINAL, www_ip="77.77.77.77"))
    wrong = base64.b64encode(b"definitely-wrong-secret").decode()
    r = run_cli(secret=wrong)
    after = q_a(WWW)
    ok = (r.returncode != 0) and (before == after)
    report("auth_failure", ok,
           f"rc={r.returncode} before={before} after={after}")


SCENARIOS = [
    s1_first_sync,
    s2_heritage_markers,
    s3_idempotency,
    s4_change_detection,
    s5_stale_deletion,
    s6_dry_run,
    s7_auth_failure,
]

for _scenario in SCENARIOS:
    try:
        _scenario()
    except SystemExit:
        raise
    except Exception as e:  # keep going so the summary lists every failure
        import traceback
        report(_scenario.__name__, False, f"EXCEPTION {type(e).__name__}: {e}\n{traceback.format_exc()}")

finish()
